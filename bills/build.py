# Builds bills/page.js from the files in bills/ (python3 bills/build.py). Served at bills.hania360.com.
import json, base64
r = lambda p: open('bills/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('bills/' + p, 'rb').read()).decode()
out = ['// Generated by bills/build.py from the files in bills/. Do not edit by hand.',
       'export default ' + json.dumps(r('bills.html'), ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '};',
       'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('bills/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
