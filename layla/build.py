# Builds layla/page.js from the files in layla/ (python3 layla/build.py). HaniaLayla, served at layla.hania360.com.
# src/app.js is inlined into layla.html; HaniaDat's calendar library (shabbat/hebcal.js) lets the app rest on Shabbat and holidays.
import json, base64, hashlib, re, subprocess
r = lambda p: open('layla/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('layla/' + p, 'rb').read()).decode()
heb = open('shabbat/hebcal.js', encoding='utf8').read()
cities = re.search(r'CITIES = (\[.*\]);', open('lib/cities.js', encoding='utf8').read()).group(1)
app = r('src/app.js').replace('/*CITIES*/[["ירושלים", 31.778, 35.235, 40]]', cities)
assert '/*CITIES*/' not in app and '</script' not in app
body = r('layla.html').replace('<script>/*APP*/</script>', '<script>' + app + '</script>').replace('<script src="/hebcal.js"></script>', '<script src="/hebcal.js?v=' + hashlib.sha1(heb.encode()).hexdigest()[:8] + '"></script>')
assert 'hebcal.js?v=' in body and '/*APP*/' not in body
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaLayla: הדקות שלפני השינה. הילד אומר לילה טוב לכוכבים עד שהירח נרדם, צלילי גשם וים ושירי ערש שנוצרים בטלפון, נשימות עם בועה, מנורת לילה עם מקרן כוכבים, וקריאת שמע על המיטה.">'
        '<link rel="canonical" href="https://layla.hania360.com/"><meta name="theme-color" content="#0B0726">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="לילה טוב"><meta name="apple-mobile-web-app-capable" content="yes">')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + '\n<script src="/install.js" data-name="HaniaLayla" data-color="#0B0726" defer></script>\n</body></html>'
out = ['// Generated by layla/build.py from the files in layla/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '  "/hebcal.js": ["text/javascript; charset=utf-8", ' + json.dumps(heb, ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('layla/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
subprocess.run(["node", "tools/assets.mjs", "layla"], check=True)
