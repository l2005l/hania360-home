# Builds smart/page.js from the files in smart/ (python3 smart/build.py). Served at smart.hania360.com.
import json, base64
r = lambda p: open('smart/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('smart/' + p, 'rb').read()).decode()
# the version: a short hash of the page; the app compares it with /ver to reload itself after an update
import hashlib
page = r('smart.html'); ver = hashlib.sha1(page.encode('utf8')).hexdigest()[:10]; page = page.replace('__VER__', ver)
out = ['// Generated by smart/build.py from the files in smart/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
              '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '  "/ver": ["text/plain; charset=utf-8", ' + json.dumps(ver) + '],',
       '  "/mini": ["text/html; charset=utf-8", ' + json.dumps(r('mini.html'), ensure_ascii=False) + '],',
       '};',
       'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('smart/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
# Pictures and big files go to Workers Static Assets (public/_a/), so the Worker stays small.
import subprocess; subprocess.run(["node", "tools/assets.mjs", "smart"], check=True)
