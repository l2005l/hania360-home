# Builds party/page.js from the files in party/ (python3 party/build.py). HaniaParty, served at party.hania360.com;
# its server side is party/room.js (words and questions in party/bank.js). src/app.js is inlined into party.html; HaniaFrame's QR library (MIT) draws the QR code,
# and HaniaDat's calendar library (shabbat/hebcal.js) lets the app rest on Shabbat and holidays.
import json, base64, hashlib, re, subprocess
r = lambda p: open('party/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('party/' + p, 'rb').read()).decode()
heb = open('shabbat/hebcal.js', encoding='utf8').read()
cities = re.search(r'CITIES = (\[.*\]);', open('lib/cities.js', encoding='utf8').read()).group(1)
app = r('src/app.js').replace('/*CITIES*/[["ירושלים", 31.778, 35.235, 40]]', cities)
assert '/*CITIES*/' not in app and '</script' not in app
qr = open('frame/vendor/qrcode.min.js', encoding='utf8').read()
body = r('party.html').replace('<script>/*APP*/</script>', '<script>' + app + '</script>').replace('<script src="/qrcode.js" defer>', '<script src="/qrcode.js?v=' + hashlib.sha1(qr.encode()).hexdigest()[:8] + '" defer>').replace('<script src="/hebcal.js" defer>', '<script src="/hebcal.js?v=' + hashlib.sha1(heb.encode()).hexdigest()[:8] + '" defer>')
assert '/*APP*/' not in body and 'qrcode.js?v=' in body
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaParty: משחקי מסיבה לכל המשפחה. המסך הגדול הוא הלוח וכל טלפון הוא שלט: מציירים ומנחשים, בלוף, ומי במשפחה הכי... בחינם, בלי הורדות ובלי הרשמה.">'
        '<link rel="canonical" href="https://party.hania360.com/"><meta name="theme-color" content="#120B2E">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="מסיבה"><meta name="apple-mobile-web-app-capable" content="yes">')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + '\n<script src="/install.js" data-name="HaniaParty" data-color="#120B2E" defer></script>\n</body></html>'
out = ['// Generated by party/build.py from the files in party/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '  "/qrcode.js": ["text/javascript; charset=utf-8", ' + json.dumps(qr, ensure_ascii=False) + '],',
       '  "/hebcal.js": ["text/javascript; charset=utf-8", ' + json.dumps(heb, ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('party/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
subprocess.run(["node", "tools/assets.mjs", "party"], check=True)
