# Builds eretz/page.js from the files in eretz/ (python3 eretz/build.py). HaniaEretz, served at eretz.hania360.com.
# src/app.js is inlined into eretz.html, with coast.json: the coastline of the region from Natural Earth's 10m land
# (public domain, through world-atlas), clipped to the box once. The land's shape, the lakes and the Jordan are in app.js.
import json, base64, subprocess
r = lambda p: open('eretz/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('eretz/' + p, 'rb').read()).decode()
app = r('src/app.js').replace('/*COAST*/[]', r('coast.json').strip())
assert '/*COAST*/' not in app and '</script' not in app
body = r('eretz.html').replace('<script>/*APP*/</script>', '<script>' + app + '</script>')
assert '/*APP*/' not in body
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaEretz: מפה מאוירת של ארץ ישראל לכל המשפחה. מקומות מהתנ״ך, מההיסטוריה ומהטבע עם סיפור קצר, מסלולים בעקבות אברהם, יעקב, דוד והמכבים, משחק ״איפה זה?״ ודרכון של מקומות שהייתם בהם.">'
        '<link rel="canonical" href="https://eretz.hania360.com/"><meta name="theme-color" content="#0E5E6F">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="מסע בארץ">')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + '\n<script src="/install.js" data-name="HaniaEretz" data-color="#0E5E6F" defer></script>\n</body></html>'
out = ['// Generated by eretz/build.py from the files in eretz/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('eretz/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
subprocess.run(["node", "tools/assets.mjs", "eretz"], check=True)
