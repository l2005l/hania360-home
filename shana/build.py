# Builds shana/page.js (python3 shana/build.py): "השנה שלנו", served at shana.hania360.com; its numbers come from /api/year (lib/year.js).
import json, base64, subprocess
b64 = lambda p: base64.b64encode(open('shana/' + p, 'rb').read()).decode()
r = lambda p: open('shana/' + p, encoding='utf8').read()
app = r('src/app.js')
assert '</script' not in app
body = r('shana.html').replace('<script>/*APP*/</script>', '<script>' + app + '</script>')
assert '/*APP*/' not in body
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="השנה שלנו: השנה של המשפחה עם Hania360, כסיפור קצר ומונפש. כוכבים, שגרות, מטלות, לימוד וכושר, ותמונה לשתף.">'
        '<link rel="canonical" href="https://shana.hania360.com/"><meta name="theme-color" content="#2B0B5E"><link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="השנה שלנו">')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + '\n</body></html>'
out = ['// Generated by shana/build.py from the files in shana/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('shana/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
subprocess.run(["node", "tools/assets.mjs", "shana"], check=True)
