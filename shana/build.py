# Builds shana/page.js (python3 shana/build.py): "השנה שלנו", served at hania360.com/shana; its numbers come from /api/year (lib/year.js).
import json
r = lambda p: open('shana/' + p, encoding='utf8').read()
app = r('src/app.js')
assert '</script' not in app
body = r('shana.html').replace('<script>/*APP*/</script>', '<script>' + app + '</script>')
assert '/*APP*/' not in body
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="השנה שלנו: השנה של המשפחה עם Hania360, כסיפור קצר ומונפש. כוכבים, שגרות, מטלות, לימוד וכושר, ותמונה לשתף.">'
        '<meta name="theme-color" content="#2B0B5E"><link rel="icon" href="/icons/icon-192.png">')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + '\n</body></html>'
open('shana/page.js', 'w', encoding='utf8').write('// Generated by shana/build.py from the files in shana/. Do not edit by hand.\nexport default ' + json.dumps(page, ensure_ascii=False) + ';\n')
