# Builds shabbat/page.js from the files in shabbat/ (python3 shabbat/build.py). HaniaDat, served at dat.hania360.com (and shabbat.hania360.com).
# home.html is the app itself; this wraps it in the page head (install, icons, offline) for the site.
import json, base64
r = lambda p: open('shabbat/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('shabbat/' + p, 'rb').read()).decode()
body = r('shabbat.html')
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaDat: התאריך העברי, זמני היום לפי העיר (נץ, סוף זמן קריאת שמע ותפילה, שקיעה וצאת הכוכבים), הזמן הבא בספירה לאחור, מצפן לכותל, זמני שבת וחג ופרשת השבוע, ותזכורות לטלפון. בחינם.">'
        '<link rel="canonical" href="https://dat.hania360.com/"><meta name="theme-color" content="#1A130E">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="HaniaDat">'
        '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}</style>')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + (
    '\n<script src="/install.js" data-name="HaniaDat" data-color="#1A130E" defer></script>'
    '\n<script>if("serviceWorker" in navigator)addEventListener("load",()=>navigator.serviceWorker.register("/sw.js").catch(()=>{}));</script>\n</body></html>')
# The <title>/<meta>/<link> lines at the top of home.html belong in the head: move the <style> into body is fine for browsers.
out = ['// Generated by shabbat/build.py from the files in shabbat/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '  "/hebcal.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('hebcal.js'), ensure_ascii=False) + '],',
       '  "/parasha.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('parasha.js'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('shabbat/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
