# Builds tv/page.js from the files in tv/ (python3 tv/build.py). HaniaTV, served at tv.hania360.com.
# Live TV and radio from official sources only; HaniaDat's calendar library (shabbat/hebcal.js) rests the screen on Shabbat and holidays.
import json, base64, hashlib
r = lambda p: open('tv/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('tv/' + p, 'rb').read()).decode()
heb = open('shabbat/hebcal.js', encoding='utf8').read()
import re as _re
cities = _re.search(r'CITIES = (\[.*\]);', open('lib/cities.js', encoding='utf8').read()).group(1)
body = r('tv.html').replace('/*CITIES*/[["ירושלים", 31.778, 35.235, 40]]', cities).replace('<script src="/hebcal.js"></script>', '<script src="/hebcal.js?v=' + hashlib.sha1(heb.encode()).hexdigest()[:8] + '"></script>')
assert 'hebcal.js?v=' in body and '/*CITIES*/' not in body
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaTV: ערוצי טלוויזיה ורדיו בשידור חי במקום אחד, בחינם. רק שידורים רשמיים וחוקיים: חדשות מישראל ומהעולם, ספורט, חלל, טבע, מוזיקה, ילדים ורדיו.">'
        '<link rel="canonical" href="https://tv.hania360.com/"><meta name="theme-color" content="#0B0F1A">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="HaniaTV">'
        '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}</style>')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + (
    '\n<script src="/install.js" data-name="HaniaTV" data-color="#0B0F1A" defer></script>'
    '\n<script>if("serviceWorker" in navigator)addEventListener("load",()=>navigator.serviceWorker.register("/sw.js").catch(()=>{}));</script>\n</body></html>')
out = ['// Generated by tv/build.py from the files in tv/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '  "/hebcal.js": ["text/javascript; charset=utf-8", ' + json.dumps(heb, ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('tv/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
# Pictures and big files go to Workers Static Assets (public/_a/), so the Worker stays small.
import subprocess; subprocess.run(["node", "tools/assets.mjs", "tv"], check=True)
