# Builds masach/page.js from the files in masach/ (python3 masach/build.py). Served at masach.hania360.com.
# home.html is the app itself; this wraps it in the page head (install, icons, offline) for the site.
import json, base64
r = lambda p: open('masach/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('masach/' + p, 'rb').read()).decode()
body = r('masach.html')
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="זמן מסך שהילד רואה: שעון שיורד על הטאבלט או על הטלוויזיה, הפסקה עם משימה בלי מסך כשנגמר, ודקות שמרוויחים. ההורים שולטים מהטלפון. בחינם.">'
        '<link rel="canonical" href="https://masach.hania360.com/"><meta name="theme-color" content="#14123A">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="HaniaMasach">'
        '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}</style>')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + (
    '\n<script src="/install.js" data-name="HaniaMasach" data-color="#14123A" defer></script>'
    '\n<script>if("serviceWorker" in navigator)addEventListener("load",()=>navigator.serviceWorker.register("/sw.js").catch(()=>{}));</script>\n</body></html>')
# The <title>/<meta>/<link> lines at the top of home.html belong in the head: move the <style> into body is fine for browsers.
out = ['// Generated by masach/build.py from the files in masach/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('masach/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
# Pictures and big files go to Workers Static Assets (public/_a/), so the Worker stays small.
import subprocess; subprocess.run(["node", "tools/assets.mjs", "masach"], check=True)
