# Builds kasefet/page.js from the files in kasefet/ (python3 kasefet/build.py). HaniaKasefet, served at kasefet.hania360.com.
# The page gets a strict Content-Security-Policy: only its own inline scripts (by SHA-256 hash) and files
# from its own address may run, nothing may be loaded from elsewhere, and no other site may frame it.
import json, base64, hashlib, re
r = lambda p: open('kasefet/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('kasefet/' + p, 'rb').read()).decode()
body = r('kasefet.html')
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaKasefet: כסף, השקעות, תקציב והבית במקום אחד. מוצפן בטלפון לפני שמשהו יוצא ממנו. ניתוח מצב, מסלולי השקעה, תזכורות. בחינם.">'
        '<link rel="canonical" href="https://kasefet.hania360.com/"><meta name="robots" content="noindex"><meta name="referrer" content="no-referrer"><meta name="theme-color" content="#0B1220">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="הכספת">'
        '<style>:root{padding-top:env(safe-area-inset-top,0px)}img{max-width:100%}</style>')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + '\n<script src="/install.js" data-name="HaniaKasefet" data-color="#0B1220" defer></script>\n</body></html>'
hashes = ["'sha256-" + base64.b64encode(hashlib.sha256(s.encode('utf8')).digest()).decode() + "'" for s in re.findall(r'<script>(.*?)</script>', page, re.S)]
csp = ("default-src 'none'; script-src 'self' " + " ".join(hashes) + "; style-src 'self' 'unsafe-inline'; img-src 'self' blob: data:; "
       "connect-src 'self'; manifest-src 'self'; worker-src 'self'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'")
out = ['// Generated by kasefet/build.py from the files in kasefet/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('kasefet/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
open('kasefet/csp.js', 'w', encoding='utf8').write('// Generated by kasefet/build.py: the page\'s Content-Security-Policy (hashes of its inline scripts).\nexport default ' + json.dumps(csp) + ';\n')
# Pictures and big files go to Workers Static Assets (public/_a/), so the Worker stays small.
import subprocess; subprocess.run(["node", "tools/assets.mjs", "kasefet"], check=True)
