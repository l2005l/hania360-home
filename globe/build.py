# Builds HaniaGlobe (python3 globe/build.py), served at globe.hania360.com:
#   globe/page.js                      the page (globe.html), manifest, service worker, icons
#   public/_a/globe.hania360.com/globe.js  d3-geo + topojson-client (ISC) + the map (data.json) + src/app.js
# data.json was made once from world-atlas countries-110m (Natural Earth, public domain) with Hebrew names from
# i18n-iso-countries (MIT) and continents from countries-list (MIT); areas are relative to Israel.
import json, base64, hashlib, os, re, subprocess
r = lambda p: open('globe/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('globe/' + p, 'rb').read()).decode()
OUT = 'public/_a/globe.hania360.com/'
os.makedirs(OUT, exist_ok=True)
app = r('src/app.js')
js = r('vendor/g3.min.js') + '\n;window.GLOBE=' + r('data.json') + ';\n' + app
open(OUT + 'globe.js', 'w', encoding='utf8').write(js)
body = r('globe.html').replace('@GV@', hashlib.sha1(js.encode()).hexdigest()[:10])
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaGlobe: כדור הארץ לילדים. מסובבים את הכדור, נוגעים במדינה וקוראים עליה בעברית: דגל, עיר בירה, גודל ועובדה מעניינת. טסים מישראל לכל מקום ומקבלים חותמת בדרכון, ומשחקים במשחקי מדינות ודגלים.">'
        '<link rel="canonical" href="https://globe.hania360.com/"><meta name="theme-color" content="#030713">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="כדור הארץ"><meta name="apple-mobile-web-app-capable" content="yes">')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + '\n<script src="/install.js" data-name="HaniaGlobe" data-color="#030713" defer></script>\n</body></html>'
out = ['// Generated by globe/build.py from the files in globe/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('globe/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
subprocess.run(["node", "tools/assets.mjs", "globe"], check=True)
