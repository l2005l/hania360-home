# Builds sport/page.js from the files in sport/ (python3 sport/build.py). HaniaSport, served at sport.hania360.com.
# Reminders use HaniaDat's reminder service (/api/shabbat/, kind "c"). Data: /api/sport/ (sport/api.js).
import json, base64
r = lambda p: open('sport/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('sport/' + p, 'rb').read()).decode()
body = r('sport.html')
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaSport: ליגת העל בכדורגל, היורוליג ודני אבדיה ב־NBA. תוצאות חיות, טבלאות, לוח משחקים ותזכורת לפני המשחק של הקבוצה שלכם. בחינם ובלי עומס.">'
        '<link rel="canonical" href="https://sport.hania360.com/"><meta name="theme-color" content="#07111F">'
        '<link rel="manifest" href="/manifest.webmanifest?v=2"><link rel="apple-touch-icon" href="/icons/apple-180.png?v=2"><link rel="icon" href="/icons/icon-192.png?v=2"><meta name="apple-mobile-web-app-title" content="הספורט שלי">'
        '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}</style>')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + (
    '\n<script src="/install.js" data-name="HaniaSport" data-color="#07111F" defer></script>'
    '\n<script>if("serviceWorker" in navigator)addEventListener("load",()=>navigator.serviceWorker.register("/sw.js").catch(()=>{}));</script>\n</body></html>')
out = ['// Generated by sport/build.py from the files in sport/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('sport/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
# Pictures and big files go to Workers Static Assets (public/_a/), so the Worker stays small.
import subprocess; subprocess.run(["node", "tools/assets.mjs", "sport"], check=True)
