# Builds frame/page.js from the files in frame/ (python3 frame/build.py). HaniaFrame, served at frame.hania360.com;
# its server side is frame/room.js. src/app.js is inlined into frame.html; vendor/qrcode.min.js (MIT) draws the QR codes,
# and HaniaDat's calendar library (shabbat/hebcal.js) tells the screen when it is Shabbat.
import json, base64, hashlib, re, subprocess
r = lambda p: open('frame/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('frame/' + p, 'rb').read()).decode()
heb = open('shabbat/hebcal.js', encoding='utf8').read()
cities = re.search(r'CITIES = (\[.*\]);', open('lib/cities.js', encoding='utf8').read()).group(1)
app = r('src/app.js').replace('/*CITIES*/[["ירושלים", 31.778, 35.235, 40]]', cities).replace('@HEBV@', hashlib.sha1(heb.encode()).hexdigest()[:8])
assert '/*CITIES*/' not in app and '@HEBV@' not in app and '</script' not in app
qr = r('vendor/qrcode.min.js')
body = r('frame.html').replace('<script>/*APP*/</script>', '<script>' + app + '</script>').replace('<script src="/qrcode.js" defer>', '<script src="/qrcode.js?v=' + hashlib.sha1(qr.encode()).hexdigest()[:8] + '" defer>')
assert '/*APP*/' not in body and 'qrcode.js?v=' in body
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaFrame: טאבלט ישן הופך למסגרת תמונות לסבא ולסבתא. כל המשפחה שולחת תמונות וברכות מהטלפון, והן מופיעות על המסך בתנועה עדינה, עם שעון ותאריך עברי. בחינם, בלי הרשמה.">'
        '<link rel="canonical" href="https://frame.hania360.com/"><meta name="theme-color" content="#8A5A34">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="המסגרת"><meta name="apple-mobile-web-app-capable" content="yes">')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + '\n<script src="/install.js" data-name="HaniaFrame" data-color="#8A5A34" defer></script>\n</body></html>'
out = ['// Generated by frame/build.py from the files in frame/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '  "/qrcode.js": ["text/javascript; charset=utf-8", ' + json.dumps(qr, ensure_ascii=False) + '],',
       '  "/hebcal.js": ["text/javascript; charset=utf-8", ' + json.dumps(heb, ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('frame/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
subprocess.run(["node", "tools/assets.mjs", "frame"], check=True)
