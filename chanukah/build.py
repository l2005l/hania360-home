# Builds chanukah/page.js from the files in chanukah/ (python3 chanukah/build.py). HaniaChanukah, served at chanukah.hania360.com.
# The calendar library is HaniaDat's (shabbat/hebcal.js); reminders use HaniaDat's reminder service (/api/shabbat/).
import json, base64, hashlib
r = lambda p: open('chanukah/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('chanukah/' + p, 'rb').read()).decode()
heb = open('shabbat/hebcal.js', encoding='utf8').read()
body = r('chanukah.html').replace('<script src="/hebcal.js"></script>', '<script src="/hebcal.js?v=' + hashlib.sha1(heb.encode()).hexdigest()[:8] + '"></script>')
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaChanukah: זמני הדלקת נרות חנוכה לפי העיר, חנוכייה להדליק יחד עם הברכות, תזכורת בכל ערב, משחק סביבון, מי מדליק הלילה, מעוז צור והסיפור לילדים. בחינם.">'
        '<link rel="canonical" href="https://chanukah.hania360.com/"><meta name="theme-color" content="#0A1430">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="חנוכה">'
        '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}</style>')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + (
    '\n<script src="/install.js" data-name="HaniaChanukah" data-color="#0A1430" defer></script>'
    '\n<script>if("serviceWorker" in navigator)addEventListener("load",()=>navigator.serviceWorker.register("/sw.js").catch(()=>{}));</script>\n</body></html>')
out = ['// Generated by chanukah/build.py from the files in chanukah/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '  "/hebcal.js": ["text/javascript; charset=utf-8", ' + json.dumps(heb, ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('chanukah/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
# Pictures and big files go to Workers Static Assets (public/_a/), so the Worker stays small.
import subprocess; subprocess.run(["node", "tools/assets.mjs", "chanukah"], check=True)
