# Builds rega/page.js from the files in rega/ (python3 rega/build.py). HaniaRega (רגע טוב), served at rega.hania360.com.
# Rooms, conversation and stories: /api/rega/ (rega/room.js).
import json, base64
r = lambda p: open('rega/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('rega/' + p, 'rb').read()).decode()
body = r('rega.html')
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaRega · רגע טוב: להעביר את הזמן בנעים בבית חולים או במיטה. משחקי זיכרון ומילים, טריוויה, נשימה מרגיעה, צלילי גשם וים, סיפורים בקול, שיחה, ותמונות והודעות מהמשפחה. בחינם, בלי הרשמה.">'
        '<link rel="canonical" href="https://rega.hania360.com/"><meta name="theme-color" content="#FBFAFF">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="רגע טוב">'
        '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}</style>')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + (
    '\n<script src="/install.js" data-name="HaniaRega" data-color="#6366F1" defer></script>'
    '\n<script>if("serviceWorker" in navigator)addEventListener("load",()=>navigator.serviceWorker.register("/sw.js").catch(()=>{}));</script>\n</body></html>')
out = ['// Generated by rega/build.py from the files in rega/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('rega/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
# Pictures and big files go to Workers Static Assets (public/_a/), so the Worker stays small.
import subprocess; subprocess.run(["node", "tools/assets.mjs", "rega"], check=True)
