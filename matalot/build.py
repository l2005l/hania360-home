# Builds matalot/page.js from the files in matalot/ (python3 matalot/build.py). HaniaMatalot, served at matalot.hania360.com.
# The texts come live from Sefaria in the browser; AI help is matalot/api.js; reminders use HaniaDat's reminder service (/api/shabbat/), and a small stand-in for HaniaDat's calendar library (shabbat/hblite.js: sunset, nightfall and the Hebrew date) to keep them out of Shabbat and holidays.
import json, base64, hashlib
r = lambda p: open('matalot/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('matalot/' + p, 'rb').read()).decode()
lite = open('shabbat/hblite.js', encoding='utf8').read()
import re as _re
cities = _re.search(r'CITIES = (\[.*\]);', open('lib/cities.js', encoding='utf8').read()).group(1)
body = r('matalot.html').replace('/*CITIES*/[["ירושלים", 31.778, 35.235, 40]]', cities).replace('<script src="/hebcal.js"></script>', '<script>' + lite + '</script>')
assert 'window.HB = { Location' in body and 'hebcal.js' not in body and '/*CITIES*/' not in body
head = ('<!doctype html><html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
        '<meta name="description" content="HaniaMatalot: מטלות הבית לילדים, בחינם. לכל ילד המטלות שלו בימים שבוחרים, סבב שבועי, נקודות לפרס או לדמי כיס, אישור הורה וסנכרון בין שני ההורים.">'
        '<link rel="canonical" href="https://matalot.hania360.com/"><meta name="theme-color" content="#0EA5E9">'
        '<link rel="manifest" href="/manifest.webmanifest"><link rel="apple-touch-icon" href="/icons/apple-180.png"><link rel="icon" href="/icons/icon-192.png"><meta name="apple-mobile-web-app-title" content="מטלות">'
        '<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}</style>')
i = body.index('<style>')
page = head + body[:i] + '</head><body>' + body[i:] + (
    '\n<script src="/install.js" data-name="HaniaMatalot" data-color="#0EA5E9" defer></script>'
    '\n<script>if("serviceWorker" in navigator)addEventListener("load",()=>navigator.serviceWorker.register("/sw.js").catch(()=>{}));</script>\n</body></html>')
out = ['// Generated by matalot/build.py from the files in matalot/. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('matalot/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
# Pictures and big files go to Workers Static Assets (public/_a/), so the Worker stays small.
import subprocess; subprocess.run(["node", "tools/assets.mjs", "matalot"], check=True)
