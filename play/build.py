# Builds play/page.js from play/play.html, the manifest and the icons (python3 play/build.py).
# The page's own og: tags are dropped; lib/growth.js adds the shared ones with the preview image.
import json, base64, re
r = lambda p: open('play/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('play/' + p, 'rb').read()).decode()
page = re.sub(r'<meta property="og:[^>]*>\n?', '', r('play.html'))
out = ['// Generated by play/build.py. Do not edit by hand.',
       'export default ' + json.dumps(page, ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '};', 'export const IMAGES = {']
for n in ('play-192.png', 'play-512.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('play/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
