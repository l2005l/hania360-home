# Builds loz/page.js from the files in loz/ (python3 loz/build.py). Served at loz.hania360.com.
import json, base64
r = lambda p: open('loz/' + p, encoding='utf8').read()
b64 = lambda p: base64.b64encode(open('loz/' + p, 'rb').read()).decode()
out = ['// Generated by loz/build.py from the files in loz/. Do not edit by hand.',
       'export default ' + json.dumps(r('loz.html'), ensure_ascii=False) + ';',
       'export const FILES = {',
       '  "/c": ["text/html; charset=utf-8", ' + json.dumps(r('c.html'), ensure_ascii=False) + '],',
       '  "/manifest.webmanifest": ["application/manifest+json", ' + json.dumps(r('manifest.webmanifest'), ensure_ascii=False) + '],',
       '  "/install.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('install.js'), ensure_ascii=False) + '],',
       '  "/sw.js": ["text/javascript; charset=utf-8", ' + json.dumps(r('sw.js'), ensure_ascii=False) + '],',
       '};',
       'export const IMAGES = {']
for n in ('icon-192.png', 'icon-512.png', 'apple-180.png'):
    out.append(f'  "/icons/{n}": "{b64("icons/" + n)}",')
out.append('};')
open('loz/page.js', 'w', encoding='utf8').write('\n'.join(out) + '\n')
# Pictures and big files go to Workers Static Assets (public/_a/), so the Worker stays small.
import subprocess; subprocess.run(["node", "tools/assets.mjs", "loz"], check=True)
